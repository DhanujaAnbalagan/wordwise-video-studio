"""FFmpeg rendering utilities for VideoFlow AI.

The renderer consumes a :class:`RenderPlan` generated by
``backend.app.media.render_plan`` and produces the final media file.

Supported features:
- video+audio, video-only, audio-only inputs
- cuts, keeps, speed changes, reordering (via the RenderPlan filters)
- captions and image overlays (via drawtext filters)
- synchronization of audio/video timestamps
- safe temporary output generation with atomic finalization and failure cleanup
- validation via FFprobe before finalizing render jobs
"""

from __future__ import annotations

import json
import os
from pathlib import Path
import shutil
import subprocess
from typing import Any, Dict, List, Optional, Union
import uuid

from ..config import get_settings
from .render_plan import CaptionOverlay, FilterStep, RenderPlan


class RenderingError(Exception):
    """Raised when FFmpeg fails or produces invalid output."""

    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code = code
        self.message = message


def _get_font_param() -> str:
    """Find a readable TTF font path to avoid fontconfig errors on Windows/Linux."""
    if os.name == "nt":
        arial = Path("C:/Windows/Fonts/arial.ttf")
        if arial.is_file():
            clean = str(arial).replace("\\", "/").replace(":", r"\:")
            return f"fontfile='{clean}':"
    else:
        for candidate in [
            Path("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"),
            Path("/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf"),
            Path("/usr/share/fonts/TTF/DejaVuSans.ttf"),
        ]:
            if candidate.is_file():
                clean = str(candidate).replace(":", r"\:")
                return f"fontfile='{clean}':"
    return ""


def escape_drawtext(text: str) -> str:
    """Safely escape text for FFmpeg drawtext filter syntax."""
    t = text.replace("\\", r"\\")
    t = t.replace("'", r"\'")
    t = t.replace(":", r"\:")
    t = t.replace("%", r"\%")
    t = t.replace(";", r"\;")
    return t


def _build_drawtext(cap: CaptionOverlay) -> str:
    """Build a drawtext filter for a single CaptionOverlay."""
    font_param = _get_font_param()
    font_size = getattr(cap, "font_size", 30) or 30
    font_color = getattr(cap, "font_color", "white") or "white"
    x = getattr(cap, "x", "(w-text_w)/2")
    y = getattr(cap, "y", "h-text_h-40")
    start_s = cap.start_ms / 1000.0
    end_s = cap.end_ms / 1000.0

    return (
        f"drawtext={font_param}text='{escape_drawtext(cap.text)}':"
        f"fontsize={font_size}:fontcolor={font_color}:"
        f"box=1:boxcolor=black@0.6:boxborderw=12:"
        f"x={x}:y={y}:"
        f"enable='between(t,{start_s:.3f},{end_s:.3f})'"
    )


def probe_media(source_path: Path) -> Dict[str, Any]:
    """Run ffprobe on source media and return parsed stream data."""
    if not source_path.is_file():
        raise RenderingError("SOURCE_MISSING", f"Source media file not found: {source_path}")

    ffprobe = shutil.which("ffprobe")
    if not ffprobe:
        raise RenderingError("FFPROBE_NOT_FOUND", "ffprobe binary not found on PATH")

    args = [
        ffprobe,
        "-v",
        "error",
        "-print_format",
        "json",
        "-show_streams",
        "-show_format",
        str(source_path),
    ]
    completed = subprocess.run(args, capture_output=True, text=True, check=False)
    if completed.returncode != 0:
        raise RenderingError("FFPROBE_FAILED", completed.stderr.strip() or "ffprobe failed on source file")

    try:
        return json.loads(completed.stdout)
    except Exception as exc:
        raise RenderingError("FFPROBE_INVALID_JSON", "Invalid JSON from ffprobe") from exc


def _run_ffmpeg(args: List[str], timeout: int) -> None:
    """Execute FFmpeg with timeout and error capture."""
    try:
        completed = subprocess.run(
            args,
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
    except subprocess.TimeoutExpired as exc:
        raise RenderingError("FFMPEG_TIMEOUT", "FFmpeg rendering timed out") from exc

    if completed.returncode != 0:
        raise RenderingError(
            "FFMPEG_FAILED",
            completed.stderr.strip() or "FFmpeg process failed",
        )


def _validate_output(output_path: Path) -> Dict[str, Any]:
    """Run ffprobe on the rendered file and return parsed JSON."""
    if not output_path.is_file() or output_path.stat().st_size == 0:
        raise RenderingError("OUTPUT_MISSING", "Rendered file not found or is empty")

    ffprobe = shutil.which("ffprobe")
    if not ffprobe:
        raise RenderingError("FFPROBE_NOT_FOUND", "ffprobe binary not found on PATH")

    args = [
        ffprobe,
        "-v",
        "error",
        "-print_format",
        "json",
        "-show_streams",
        "-show_format",
        str(output_path),
    ]
    completed = subprocess.run(args, capture_output=True, text=True, check=False)
    if completed.returncode != 0:
        raise RenderingError("FFPROBE_FAILED", completed.stderr.strip() or "ffprobe failed on output")

    try:
        data = json.loads(completed.stdout)
    except Exception as exc:
        raise RenderingError("FFPROBE_INVALID_JSON", "Invalid JSON from ffprobe") from exc

    streams = data.get("streams", [])
    if not streams:
        raise RenderingError("NO_STREAMS", "Rendered file contains no streams")

    return data


def render_job(job_id: str, source_path: Path, plan: RenderPlan) -> Path:
    """Execute rendering for a job.

    Parameters
    ----------
    job_id : str
        Identifier of the background job.
    source_path : Path
        Absolute path to the original source media.
    plan : RenderPlan
        Deterministic plan describing the filter graph and any caption/overlay metadata.

    Returns
    -------
    Path
        Path to the finalized output file in ``settings.data_dir / 'renders'``.
    """
    settings = get_settings()
    ffmpeg = shutil.which("ffmpeg")
    if not ffmpeg:
        raise RenderingError("FFMPEG_NOT_FOUND", "ffmpeg binary not found on PATH")

    # Probe input media to identify streams
    probe_data = probe_media(source_path)
    streams = probe_data.get("streams", [])
    has_video = any(s.get("codec_type") == "video" for s in streams)
    has_audio = any(s.get("codec_type") == "audio" for s in streams)

    if not has_video and not has_audio:
        raise RenderingError("NO_STREAMS", "Source media contains neither video nor audio streams")

    # Build filter complex parts
    filter_parts: List[str] = []
    v_labels: List[str] = []
    a_labels: List[str] = []

    for idx, step in enumerate(plan.filter_steps):
        # Video stream
        if has_video and step.video_filter:
            filter_parts.append(f"[0:v]{step.video_filter}[v{idx}]")
            v_labels.append(f"[v{idx}]")

        # Audio stream
        if has_audio and step.audio_filter:
            filter_parts.append(f"[0:a]{step.audio_filter}[a{idx}]")
            a_labels.append(f"[a{idx}]")

    # Concatenate or route video streams
    cur_v: Optional[str] = None
    if len(v_labels) > 1:
        concat_v = "".join(v_labels)
        filter_parts.append(f"{concat_v}concat=n={len(v_labels)}:v=1:a=0[vc]")
        cur_v = "[vc]"
    elif len(v_labels) == 1:
        cur_v = v_labels[0]

    # Concatenate or route audio streams
    cur_a: Optional[str] = None
    if len(a_labels) > 1:
        concat_a = "".join(a_labels)
        filter_parts.append(f"{concat_a}concat=n={len(a_labels)}:v=0:a=1[ac]")
        cur_a = "[ac]"
    elif len(a_labels) == 1:
        cur_a = a_labels[0]

    # Captions and text overlays (only applicable if video exists)
    if cur_v and (plan.captions or plan.overlays):
        all_overlays = list(plan.captions or []) + list(plan.overlays or [])
        for idx, cap in enumerate(all_overlays):
            dt = _build_drawtext(cap)
            next_v = f"[v_text_{idx}]"
            filter_parts.append(f"{cur_v}{dt}{next_v}")
            cur_v = next_v

    # Output file extension
    if cur_v or (has_video and not plan.filter_steps):
        ext = ".mp4"
    elif cur_a or (has_audio and not plan.filter_steps):
        src_ext = source_path.suffix.lower()
        ext = src_ext if src_ext in [".m4a", ".aac", ".mp3", ".wav"] else ".m4a"
    else:
        ext = ".mp4"

    tmp_dir = settings.data_dir / "tmp_render"
    tmp_dir.mkdir(parents=True, exist_ok=True)
    tmp_path = tmp_dir / f"{uuid.uuid4().hex}{ext}"

    args: List[str] = [
        ffmpeg,
        "-y",
        "-i",
        str(source_path),
    ]

    if filter_parts:
        args += ["-filter_complex", ";".join(filter_parts)]

    # Map video output
    if cur_v:
        args += ["-map", cur_v, "-c:v", "libx264", "-pix_fmt", "yuv420p"]
    elif has_video and not plan.filter_steps:
        args += ["-map", "0:v", "-c:v", "libx264", "-pix_fmt", "yuv420p"]

    # Map audio output
    if cur_a:
        args += ["-map", cur_a, "-c:a", "aac"]
    elif has_audio and not plan.filter_steps:
        args += ["-map", "0:a", "-c:a", "aac"]

    args.append(str(tmp_path))

    try:
        _run_ffmpeg(args, timeout=settings.job_timeout_s)
        _validate_output(tmp_path)

        final_dir = settings.data_dir / "renders"
        final_dir.mkdir(parents=True, exist_ok=True)
        final_path = final_dir / f"{job_id}{ext}"
        tmp_path.replace(final_path)
        return final_path
    finally:
        if tmp_path.is_file():
            try:
                tmp_path.unlink()
            except OSError:
                pass
