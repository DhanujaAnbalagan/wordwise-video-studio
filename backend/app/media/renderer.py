"""FFmpeg rendering utilities.

The renderer consumes a :class:`RenderPlan` generated by
``backend.app.media.render_plan`` and produces the final media file.
It works with the background‑job system – a job is marked ``running``
while rendering, progress is updated, and on success the output is
atomically moved into the project's media storage.

Supported features:
- video+audio, video‑only, audio‑only inputs
- cuts, keeps, speed changes, reordering (via the RenderPlan filters)
- captions and image overlays (the plan supplies ``CaptionOverlay``
  descriptors that are turned into ``drawtext``/``overlay`` filters)
- synchronization of audio/video timestamps
"""

from __future__ import annotations

import os
import shutil
import subprocess
import uuid
from pathlib import Path
from typing import List, Dict, Any

from .render_plan import RenderPlan, FilterStep, CaptionOverlay
from ..config import get_settings
from .jobs import JobRunner, update_progress


class RenderingError(Exception):
    """Raised when FFmpeg fails or produces invalid output."""

    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code = code
        self.message = message


def _run_ffmpeg(args: List[str], timeout: int) -> None:
    try:
        completed = subprocess.run(
            args,
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
    except subprocess.TimeoutExpired as exc:
        raise RenderingError("FFMPEG_TIMEOUT", "FFmpeg rendering timed out") from exc
    if completed.returncode != 0:
        raise RenderingError(
            "FFMPEG_FAILED",
            completed.stderr.strip() or "FFmpeg process failed",
        )


def _validate_output(output_path: Path) -> Dict[str, Any]:
    """Run ffprobe on the rendered file and return parsed JSON.

    The function raises :class:`RenderingError` if ffprobe cannot be run or
    the output does not contain at least one stream.
    """
    if not output_path.is_file():
        raise RenderingError("OUTPUT_MISSING", "Rendered file not found")
    ffprobe = shutil.which("ffprobe")
    if not ffprobe:
        raise RenderingError("FFPROBE_NOT_FOUND", "ffprobe binary not found on PATH")
    args = [
        ffprobe,
        "-v",
        "error",
        "-print_format",
        "json",
        "-show_streams",
        str(output_path),
    ]
    completed = subprocess.run(args, capture_output=True, text=True, check=False)
    if completed.returncode != 0:
        raise RenderingError("FFPROBE_FAILED", completed.stderr.strip() or "ffprobe failed")
    try:
        data = json.loads(completed.stdout)
    except Exception as exc:
        raise RenderingError("FFPROBE_INVALID_JSON", "Invalid JSON from ffprobe") from exc
    streams = data.get("streams", [])
    if not streams:
        raise RenderingError("NO_STREAMS", "Rendered file contains no streams")
    return data


def render_job(job_id: str, source_path: Path, plan: RenderPlan) -> Path:
    """Execute rendering for a job.

    Parameters
    ----------
    job_id: str
        Identifier of the background job (used for progress updates).
    source_path: Path
        Absolute path to the original uploaded media.
    plan: RenderPlan
        Deterministic plan describing the filter graph and any caption/overlay
        metadata.

    Returns
    -------
    Path
        Path to the finalized output file (inside ``settings.data_dir``).
    """
    settings = get_settings()
    ffmpeg = shutil.which("ffmpeg")
    if not ffmpeg:
        raise RenderingError("FFMPEG_NOT_FOUND", "ffmpeg binary not on PATH")

    # Temporary output file – use a random UUID to avoid collisions.
    tmp_dir = settings.data_dir / "tmp_render"
    tmp_dir.mkdir(parents=True, exist_ok=True)
    tmp_path = tmp_dir / f"{uuid.uuid4().hex}.mp4"

    # Build filter_complex string from the plan.
    filter_parts: List[str] = []
    # Map each FilterStep to a named stream for later concatenation.
    for idx, step in enumerate(plan.filter_steps):
        # Example: "[0:v]trim=start=START:end=END,setpts=PTS-STARTPTS[v{idx}]"
        # Video stream
        if step.video_filter:
            filter_parts.append(
                f"[0:v]{step.video_filter}[v{idx}]"
            )
        # Audio stream
        if step.audio_filter:
            filter_parts.append(
                f"[0:a]{step.audio_filter}[a{idx}]"
            )
    # Concatenate video and audio streams if more than one.
    video_streams = "".join(f"[v{i}]" for i in range(len(plan.filter_steps)) if plan.filter_steps[i].video_filter)
    audio_streams = "".join(f"[a{i}]" for i in range(len(plan.filter_steps)) if plan.filter_steps[i].audio_filter)
    concat_parts = []
    if video_streams:
        concat_parts.append(f"{video_streams}concat=n={len([s for s in plan.filter_steps if s.video_filter])}:v=1:a=0[vt]")
    if audio_streams:
        concat_parts.append(f"{audio_streams}concat=n={len([s for s in plan.filter_steps if s.audio_filter])}:v=0:a=1[at]")
    # Add caption/overlay filters – simplistic implementation using drawtext.
    overlay_parts: List[str] = []
    for idx, cap in enumerate(plan.captions):
        # Assume cap has fields: text, start_ms, end_ms, x, y
        drawtext = (
            f"drawtext=text='{cap.text}':enable='between(t,{cap.start_ms/1000},{cap.end_ms/1000})':x={cap.x}:y={cap.y}"
        )
        overlay_parts.append(f"[vt]{drawtext}[v{idx}t]")
        video_streams = f"[v{idx}t]"
    # Assemble final filter_complex
    filter_complex = ";".join(filter_parts + concat_parts + overlay_parts)

    args = [
        ffmpeg,
        "-y",  # overwrite
        "-i",
        str(source_path),
    ]
    if filter_complex:
        args += ["-filter_complex", filter_complex]
    # Map outputs
    if video_streams:
        args += ["-map", "[vt]"]
    if audio_streams:
        args += ["-map", "[at]"]
    # Simple codecs – copy when possible.
    args += ["-c:v", "libx264", "-c:a", "aac", str(tmp_path)]

    # Run ffmpeg with the global job timeout.
    _run_ffmpeg(args, timeout=settings.job_timeout_s)
    # Validate output.
    _validate_output(tmp_path)

    # Atomically move to final location – use job_id as filename.
    final_dir = settings.data_dir / "renders"
    final_dir.mkdir(parents=True, exist_ok=True)
    final_path = final_dir / f"{job_id}.mp4"
    # Ensure atomic replace.
    tmp_path.replace(final_path)
    return final_path
